#!/usr/bin/env bash
# Прогон батчей через Codex (gpt-5.5). Второй независимый движок перевода.
#   tools/mt_codex.sh [параллельных_процессов] [batch|batch-en]
# batch-en — перевод с английского: независимая проверка через второй язык.
set -u
cd "$(dirname "$0")/.."
JOBS="${1:-4}"
PREFIX="${2:-batch}"
GLOSSARY="$(cat .mt/glossary.txt)"
if [ "$PREFIX" = "batch-en" ]; then
  SRC_LANG="английского"; TAG="codex-en"
else
  SRC_LANG="русского"; TAG="codex"
fi

run_batch() {
  local batch="$1"
  local n out
  n="$(basename "$batch" .json | sed "s/${PREFIX}-//")"
  out=".mt/out-${TAG}-${n}.raw"
  [ -s "$out" ] && { echo "skip $n"; return; }

  local prompt
  prompt=$(cat <<EOF
Ты профессиональный переводчик с $SRC_LANG на грузинский язык. Переводишь сайт TPI LUX —
компании световых решений и инженерных систем в Грузии. Аудитория: заказчики
B2B и госсектор (девелоперы, муниципалитеты, отели). Тон: премиальный,
сдержанный, инженерно точный. Не буквальный подстрочник, а живой грузинский.

ЖЁСТКИЕ ПРАВИЛА
1. Пиши ТОЛЬКО мхедрули. Ни одной кириллической буквы внутри грузинского слова —
   это главный дефект машинного перевода, он недопустим.
2. Не осталось слов исходного языка вообще.
3. Латиница допустима только для марок и техтерминов: TPI LUX, LED, DMX, DALI,
   KNX, RGB, IP65, Wi-Fi, B2B.
4. HTML-сущности (&nbsp; &mdash; &laquo;) переноси в перевод без изменений,
   столько же и такие же.
5. Числа, единицы измерения и проценты сохраняй как есть.
6. Если у строки есть поле "limit" — это предел в символах для кнопки или пункта
   меню, уложись в него, жертвуя дословностью.
7. Соблюдай глоссарий ниже дословно.
8. В грузинском нет заглавных букв — не пытайся имитировать КАПС.

ГЛОССАРИЙ (русский = грузинский)
$GLOSSARY

СТРОКИ (поле "where" — где текст стоит на странице, это контекст, не переводить)
$(cat "$batch")

ОТВЕТ: только JSON-массив, без пояснений, без markdown-ограды, вида
[{"id":"a7d95f67","ka":"..."}]
по одному объекту на каждую входную строку, в том же порядке.
EOF
)
  codex exec --skip-git-repo-check --sandbox read-only -o "$out" "$prompt" >/dev/null 2>&1
  if [ -s "$out" ]; then echo "ok   $n ($(wc -c <"$out") б)"; else echo "FAIL $n"; fi
}
export -f run_batch
export GLOSSARY PREFIX TAG SRC_LANG

ls .mt/${PREFIX}-[0-9]*.json | xargs -P "$JOBS" -I{} bash -c 'run_batch "$@"' _ {}
echo "готово: $(ls .mt/out-${TAG}-*.raw 2>/dev/null | wc -l) файлов"
